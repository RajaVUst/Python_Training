num1 = float(input("Enter first number: ")) 
num2 = float(input("Enter second number: "))
result1 = num1 + num2
print(f"The sum of {num1} and {num2} is: {result1}")
result2 = num1 - num2
print(f"The difference of {num1} and {num2} is: {result2}")
result3 = num1 * num2
print(f"The product of {num1} and {num2} is: {result3}")
result4 = num1 / num2   
print(f"The quotient of {num1} and {num2} is: {result4}")