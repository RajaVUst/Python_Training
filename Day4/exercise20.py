def fizzbuzz_range(start, end):
    for n in range(start, end + 1):

        if n % 15 == 0:
            print("FizzBuzz")
        elif n % 3 == 0:
            print("Fizz")
        elif n % 5 == 0:
            print("Buzz")
        else:
            print(n)


fizzbuzz_range(1, 20)

