# FizzBuzz 
def fizzbuzz_range(start, end):

    for number in range(start, end + 1):
        if number % 3 == 0 and number % 5 == 0:
            print("FizzBuzz")
        elif number % 3 == 0:
            print("Fizz")
        elif number % 5 == 0:
            print("Buzz")
        else:
            print(number)

fizzbuzz_range(1, 20)

