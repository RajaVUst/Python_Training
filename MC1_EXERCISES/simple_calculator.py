num1 = float(input("Enter first number: ")) 
num2 = float(input("Enter second number: ")) 

sum = num1 + num2
sub = num1 - num2
mul = num1 * num2
div = num1 / num2

# This is to perform addition
print(f"The sum of {num1} and {num2} is: {sum}")
# This is to perform subtraction
print(f"The difference of {num1} and {num2} is: {sub}")
# This is to perform multiplication
print(f"The product of {num1} and {num2} is: {mul}")
# This is to perform division
print(f"The quotient of {num1} and {num2} is: {div}")